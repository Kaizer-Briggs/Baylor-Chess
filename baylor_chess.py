    font = pygame.font.SysFont("arial", 20)
    small_font = pygame.font.SysFont("arial", 16)
    big_font = pygame.font.SysFont("arial", 36, bold=True)
    images = load_piece_images(SQUARE_SIZE)
    small_images = load_piece_images(SB_CAP_ICON)

    mode, difficulty, names, time_control = get_player_setup(screen, font, big_font)
    bot_color = (not HUMAN_COLOR) if mode == "bot" else None
    get_bot_move = BOT_MOVE_FUNCS[difficulty] if mode == "bot" else None

    screen = pygame.display.set_mode(GAME_WINDOW_SIZE)

    history = [{"fen": board.fen(), "san": None, "move_uci": None, "captured_white": [], "captured_black": []}]
    view_index = 0
    scroll_offset = 0

    clocks = {chess.WHITE: time_control, chess.BLACK: time_control} if time_control is not None else None
    time_forfeit_winner = None
    resigned_color = None

    selected_square = None
    legal_targets = []
    clock = pygame.time.Clock()
    running = True

    while running:
        dt = clock.tick(30)
        over = board.is_game_over() or time_forfeit_winner is not None or resigned_color is not None
        is_bot_turn = mode == "bot" and board.turn == bot_color
        is_live = view_index == len(history) - 1

        if clocks is not None and not over:
            clocks[board.turn] -= dt / 1000.0
            if clocks[board.turn] <= 0:
                clocks[board.turn] = 0
                time_forfeit_winner = not board.turn
                over = True

        mouse_pos = pygame.mouse.get_pos()

        for event in pygame.event.get():
            if event.type == pygame.QUIT:
                running = False

            elif event.type == pygame.KEYDOWN:
                if event.key == pygame.K_LEFT:
                    view_index = max(0, view_index - 1)
                    selected_square, legal_targets = None, []
                elif event.key == pygame.K_RIGHT:
                    view_index = min(len(history) - 1, view_index + 1)
                    selected_square, legal_targets = None, []
                elif event.key == pygame.K_HOME:
                    view_index = 0
                    selected_square, legal_targets = None, []
                elif event.key == pygame.K_END:
                    view_index = len(history) - 1
                    selected_square, legal_targets = None, []

            elif event.type == pygame.MOUSEBUTTONDOWN:
                if not over and event.pos[0] >= SB_X and SB_RESIGN_BTN.collidepoint(event.pos):
                    resigned_color = board.turn if mode == "human" else HUMAN_COLOR
                elif over and REVIEW_BTN_RECT.collidepoint(event.pos):
                    analysis = run_analysis_with_progress(screen, font, big_font, history)
                    save_game_review(analysis, names)
                    run_review_screen(screen, font, small_font, big_font, images, history, analysis)
                elif event.pos[0] >= BOARD_SIZE:
                    new_index = sidebar_click(event.pos, history, scroll_offset)
                    if new_index is not None:
                        view_index = new_index
                        selected_square, legal_targets = None, []
                elif not over and not is_bot_turn and is_live:
                    square = pixel_to_square(event.pos)
                    if square is None:
                        continue

                    if selected_square is not None and square in legal_targets:
                        move = chess.Move.from_uci(move_uci(board, selected_square, square))
                        old_last = len(history) - 1
                        was_live = view_index == old_last
                        record_move(board, move, history)
                        if was_live:
                            view_index = len(history) - 1
                        selected_square, legal_targets = None, []
                    else:
                        piece = board.piece_at(square)
                        if piece and piece.color == board.turn:
                            selected_square = square
                            legal_targets = [m.to_square for m in board.legal_moves if m.from_square == square]
                        else:
                            selected_square, legal_targets = None, []

        if not running:
            break

        scroll_offset = clamp_scroll(scroll_offset, view_index)
        view_board = chess.Board(history[view_index]["fen"])

        draw_board(screen, view_board, images, selected_square if is_live else None,
                   legal_targets if is_live else [])
        draw_coordinates(screen, small_font)
        draw_sidebar(screen, font, small_font, small_images, history, view_index, scroll_offset,
                     clocks, names, board.turn)
        draw_status(screen, font, status_text(board, names, is_bot_turn, is_live))
        if not over:
            draw_resign_button(screen, small_font, mouse_pos)
        else:
            draw_end_banner(screen, big_font, font, board, names, time_forfeit_winner, resigned_color, mouse_pos)
        pygame.display.flip()

        if running and not over and is_bot_turn:
            pygame.time.delay(300)
            old_last = len(history) - 1
            was_live = view_index == old_last
            record_move(board, get_bot_move(board, bot_color), history)
            if was_live:
                view_index = len(history) - 1


def draw_eval_graph(screen, eval_history, view_index, rect):
    pygame.draw.rect(screen, SIDEBAR_BG, rect)
    if len(eval_history) < 2:
        return
    max_abs = max(200, max(abs(e) for e in eval_history))
    mid_y = rect.y + rect.height // 2
    pygame.draw.line(screen, WHITE_TEXT, (rect.x, mid_y), (rect.x + rect.width, mid_y), 1)

    points = []
    for i, e in enumerate(eval_history):
        x = rect.x + int(i / (len(eval_history) - 1) * rect.width)
        y = mid_y - int((e / max_abs) * (rect.height // 2 - 4))
        points.append((x, y))
    pygame.draw.lines(screen, BAYLOR_GOLD, False, points, 2)

    vx = rect.x + int(view_index / (len(eval_history) - 1) * rect.width)
    pygame.draw.line(screen, WHITE_TEXT, (vx, rect.y), (vx, rect.y + rect.height), 1)



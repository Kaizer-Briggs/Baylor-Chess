def text_input_screen(screen, font, big_font, prompt, max_len=20):
    text = ""
    box_rect = pygame.Rect(BOARD_SIZE // 2 - 160, 250, 320, 50)
    clock = pygame.time.Clock()

    while True:
        for event in pygame.event.get():
            if event.type == pygame.QUIT:
                pygame.quit()
                sys.exit()
            if event.type == pygame.KEYDOWN:
                if event.key == pygame.K_RETURN:
                    return text.strip()
                elif event.key == pygame.K_BACKSPACE:
                    text = text[:-1]
                elif len(text) < max_len and event.unicode.isprintable():
                    text += event.unicode

        screen.fill(BAYLOR_GREEN)
        title = big_font.render("Baylor Chess", True, BAYLOR_GOLD)
        screen.blit(title, title.get_rect(center=(BOARD_SIZE // 2, 120)))
        prompt_label = font.render(prompt, True, WHITE_TEXT)
        screen.blit(prompt_label, prompt_label.get_rect(center=(BOARD_SIZE // 2, 190)))

        pygame.draw.rect(screen, BAYLOR_GOLD, box_rect, border_radius=8)
        text_surface = font.render(text, True, BAYLOR_GREEN)
        screen.blit(text_surface, (box_rect.x + 12, box_rect.y + 14))

        hint = font.render("Press Enter to continue", True, WHITE_TEXT)
        screen.blit(hint, hint.get_rect(center=(BOARD_SIZE // 2, 340)))

        pygame.display.flip()
        clock.tick(30)



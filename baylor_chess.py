def load_piece_images(size):
    images = {}
    for key, name in PIECE_NAME_MAP.items():
        path = os.path.join(PIECE_DIR, f"{name}.png")
        img = pygame.image.load(path).convert_alpha()
        images[key] = pygame.transform.smoothscale(img, (size, size))
    return images


def square_to_pixel(square):
    file = chess.square_file(square)
    rank = chess.square_rank(square)
    if HUMAN_COLOR == chess.BLACK:
        col, row = 7 - file, rank
    else:
        col, row = file, 7 - rank
    return col * SQUARE_SIZE, row * SQUARE_SIZE


def pixel_to_square(pos):
    x, y = pos
    if y >= BOARD_SIZE or x >= BOARD_SIZE:
        return None
    col, row = x // SQUARE_SIZE, y // SQUARE_SIZE
    if HUMAN_COLOR == chess.BLACK:
        file, rank = 7 - col, row
    else:
        file, rank = col, 7 - row
    return chess.square(file, rank)


def draw_board(screen, view_board, images, selected_square, legal_targets):
    for rank in range(8):
        for file in range(8):
            square = chess.square(file, rank)
            x, y = square_to_pixel(square)
            is_light = (file + rank) % 2 == 1
            color = LIGHT_SQUARE if is_light else DARK_SQUARE
            pygame.draw.rect(screen, color, (x, y, SQUARE_SIZE, SQUARE_SIZE))

    if selected_square is not None:
        x, y = square_to_pixel(selected_square)
        pygame.draw.rect(screen, HIGHLIGHT, (x, y, SQUARE_SIZE, SQUARE_SIZE), 4)

    for target in legal_targets:
        x, y = square_to_pixel(target)
        center = (x + SQUARE_SIZE // 2, y + SQUARE_SIZE // 2)
        pygame.draw.circle(screen, MOVE_DOT, center, 10)

    for square in chess.SQUARES:
        piece = view_board.piece_at(square)
        if piece:
            x, y = square_to_pixel(square)
            screen.blit(images[(piece.color, piece.piece_type)], (x, y))



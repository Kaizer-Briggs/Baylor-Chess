def coin_flip_screen(screen, font, big_font, player1, player2):
    flip_btn = pygame.Rect(BOARD_SIZE // 2 - 110, 260, 220, 60)
    continue_btn = pygame.Rect(BOARD_SIZE // 2 - 110, 340, 220, 50)
    result = None

    while True:
        for event in pygame.event.get():
            if event.type == pygame.QUIT:
                pygame.quit()
                sys.exit()
            if event.type == pygame.MOUSEBUTTONDOWN:
                if result is None and flip_btn.collidepoint(event.pos):
                    result = random.choice([(player1, player2), (player2, player1)])
                elif result is not None and continue_btn.collidepoint(event.pos):
                    return {chess.WHITE: result[0], chess.BLACK: result[1]}

        screen.fill(BAYLOR_GREEN)
        title = big_font.render("Baylor Chess", True, BAYLOR_GOLD)
        screen.blit(title, title.get_rect(center=(BOARD_SIZE // 2, 130)))
        mouse_pos = pygame.mouse.get_pos()

        if result is None:
            subtitle = font.render("Flip a coin to decide colors", True, WHITE_TEXT)
            screen.blit(subtitle, subtitle.get_rect(center=(BOARD_SIZE // 2, 190)))
            hovered = flip_btn.collidepoint(mouse_pos)
            color = WHITE_TEXT if hovered else BAYLOR_GOLD
            pygame.draw.rect(screen, color, flip_btn, border_radius=12)
            label = font.render("Flip Coin", True, BAYLOR_GREEN)
            screen.blit(label, label.get_rect(center=flip_btn.center))
        else:
            white_name, black_name = result
            res_text = font.render(f"{white_name} is White  -  {black_name} is Black", True, BAYLOR_GOLD)
            screen.blit(res_text, res_text.get_rect(center=(BOARD_SIZE // 2, 220)))
            hovered = continue_btn.collidepoint(mouse_pos)
            color = WHITE_TEXT if hovered else BAYLOR_GOLD
            pygame.draw.rect(screen, color, continue_btn, border_radius=12)
            label = font.render("Continue", True, BAYLOR_GREEN)
            screen.blit(label, label.get_rect(center=continue_btn.center))

        pygame.display.flip()
        pygame.time.delay(16)


def get_player_setup(screen, font, big_font):
    mode = choose_mode(screen, font, big_font)

    if mode == "bot":
        player_name = text_input_screen(screen, font, big_font, "Enter your name:") or "Player"
        difficulty = choose_difficulty(screen, font, big_font)
        names = {
            HUMAN_COLOR: player_name,
            not HUMAN_COLOR: f"Bot ({difficulty})",
        }
        time_control = choose_timer_control(screen, font, big_font)
        return mode, difficulty, names, time_control

    player1 = text_input_screen(screen, font, big_font, "Player 1, enter your name:") or "Player 1"
    player2 = text_input_screen(screen, font, big_font, "Player 2, enter your name:") or "Player 2"
    names = coin_flip_screen(screen, font, big_font, player1, player2)
    time_control = choose_timer_control(screen, font, big_font)
    return mode, None, names, time_control


def outcome_title(outcome, names):
    if outcome.winner is None:
        return "Draw!"
    winner_name = names[outcome.winner]
    if outcome.termination == chess.Termination.CHECKMATE:
        return f"Checkmate! {winner_name} wins"
    return f"{winner_name} wins"



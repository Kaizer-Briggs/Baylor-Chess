def move_uci(board, from_sq, to_sq):
    piece = board.piece_at(from_sq)
    uci = chess.square_name(from_sq) + chess.square_name(to_sq)
    if piece and piece.piece_type == chess.PAWN and chess.square_rank(to_sq) in (0, 7):
        uci += "q"
    return uci


def get_captured_piece(board, move):
    """Must be called BEFORE board.push(move)."""
    if board.is_en_passant(move):
        return chess.Piece(chess.PAWN, not board.turn)
    return board.piece_at(move.to_square)


def record_move(board, move, history):
    """Pushes move onto board and appends a snapshot to history."""
    captured = get_captured_piece(board, move)
    san = board.san(move)
    move_uci_str = move.uci()
    captured_white = list(history[-1]["captured_white"])
    captured_black = list(history[-1]["captured_black"])
    board.push(move)
    if captured:
        if captured.color == chess.WHITE:
            captured_white.append(captured.piece_type)
        else:
            captured_black.append(captured.piece_type)
    history.append({
        "fen": board.fen(),
        "san": san,
        "move_uci": move_uci_str,
        "captured_white": captured_white,
        "captured_black": captured_black,
    })



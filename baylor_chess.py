def pst_value(piece_type, square, color):
    file = chess.square_file(square)
    rank = chess.square_rank(square)
    idx = (7 - rank) * 8 + file if color == chess.WHITE else rank * 8 + file
    return PST[piece_type][idx]


def material_eval(board, color):
    score = 0
    for pt, value in PIECE_VALUES.items():
        score += value * (len(board.pieces(pt, color)) - len(board.pieces(pt, not color)))
    return score


def positional_eval(board, color):
    score = 0
    for square in chess.SQUARES:
        piece = board.piece_at(square)
        if piece is None:
            continue
        value = PIECE_VALUES.get(piece.piece_type, 0) * 100 + pst_value(piece.piece_type, square, piece.color)
        score += value if piece.color == color else -value
    mobility = board.legal_moves.count()
    score += mobility if board.turn == color else -mobility
    return score


def random_move(board):
    return random.choice(list(board.legal_moves))


def minimax(board, depth, color):
    if depth == 0 or board.is_game_over():
        return material_eval(board, color)
    best = float("-inf")
    for move in board.legal_moves:
        board.push(move)
        best = max(best, -minimax(board, depth - 1, not color))
        board.pop()
    return best


def alpha_beta(board, depth, alpha, beta, color, eval_fn):
    if depth == 0 or board.is_game_over():
        return eval_fn(board, color)
    for move in board.legal_moves:
        board.push(move)
        alpha = max(alpha, -alpha_beta(board, depth - 1, -beta, -alpha, not color, eval_fn))
        board.pop()
        if alpha >= beta:
            break
    return alpha


def pick_best_move(board, color, score_after_move):
    best_move, best_score = None, float("-inf")
    for move in board.legal_moves:
        board.push(move)
        score = -score_after_move(board)
        board.pop()
        if score > best_score:
            best_score = score
            best_move = move
    return best_move


def easy_bot_move(board, color):
    return random_move(board)


def medium_bot_move(board, color):
    depth = 2
    return pick_best_move(board, color, lambda b: minimax(b, depth - 1, not color))


def hard_bot_move(board, color):
    depth = 4
    return pick_best_move(
        board, color,
        lambda b: alpha_beta(b, depth - 1, float("-inf"), float("inf"), not color, material_eval),
    )


def bear_bot_move(board, color):
    depth = 4
    return pick_best_move(
        board, color,
        lambda b: alpha_beta(b, depth - 1, float("-inf"), float("inf"), not color, positional_eval),
    )


